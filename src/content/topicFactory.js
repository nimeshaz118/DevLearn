import { callout, code, diagram, heading, list, quiz, text } from '../utils/contentParser.js'

export const createLesson = ({
  id,
  title,
  description,
  category,
  tags,
  minutes = 9,
  overview,
  diagramTitle,
  diagramSteps,
  diagramCaption,
  concepts,
  exampleIntro,
  language,
  filename,
  example,
  takeaway,
  quizQuestion,
  quizOptions,
  quizAnswer,
  quizExplanation,
}) => ({
  id,
  title,
  description,
  category,
  tags,
  status: 'published',
  date: '2026-10-27',
  estimatedReadTime: minutes,
  sections: [
    heading(1, title),
    text(overview),
    diagram(diagramTitle, diagramSteps, diagramCaption),
    heading(2, 'Key ideas'),
    list(concepts),
    heading(2, 'Practical example'),
    text(exampleIntro),
    code(language, example, filename),
    callout(takeaway, 'tip'),
    quiz(quizQuestion, quizOptions, quizAnswer, quizExplanation),
  ],
})
